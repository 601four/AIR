const CJK = /[\u4e00-\u9fff]/

export function hasChinese(value: string): boolean {
	return CJK.test(value)
}

export function translateSearchQuery(input: string): string {
	const query = input.trim().toLowerCase()
	if (!query || !CJK.test(query)) return input
	if (ALIASES[query]) return ALIASES[query]
	const parts: string[] = []
	for (const [zh, en] of Object.entries(ALIASES)) {
		if (query.includes(zh)) parts.push(en)
	}
	if (parts.length > 0) return Array.from(new Set(parts)).join(' ')
	return input
}
